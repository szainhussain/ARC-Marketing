"""Provider-neutral object storage + upload validation.

LocalStorage keeps files under UPLOAD_DIR with random keys (the original
filename is never used as a path). SupabaseStorage keeps them in a private
Supabase Storage bucket (STORAGE_BACKEND=supabase), which survives restarts
on hosts with a temporary disk such as Render. Both expose put/get/delete.
"""

import hashlib
import os
import re
import urllib.error
import urllib.parse
import urllib.request
import uuid

from flask import current_app

from app.services.errors import ServiceUnavailable

# extension -> (allowed content types, magic-byte prefixes or None for text)
ALLOWED = {
    "png": ({"image/png"}, [b"\x89PNG\r\n\x1a\n"]),
    "jpg": ({"image/jpeg"}, [b"\xff\xd8\xff"]),
    "jpeg": ({"image/jpeg"}, [b"\xff\xd8\xff"]),
    "gif": ({"image/gif"}, [b"GIF87a", b"GIF89a"]),
    "webp": ({"image/webp"}, [b"RIFF"]),
    "pdf": ({"application/pdf"}, [b"%PDF-"]),
    "txt": ({"text/plain"}, None),
    "md": ({"text/markdown", "text/plain"}, None),
    "csv": ({"text/csv", "text/plain", "application/vnd.ms-excel"}, None),
}


class UploadRejected(Exception):
    pass


def validate_upload(filename: str, content_type: str, data: bytes) -> str:
    """Returns a normalised extension or raises UploadRejected."""

    name = os.path.basename(filename or "").strip()
    if not name or "." not in name:
        raise UploadRejected("File must have an extension.")
    ext = name.rsplit(".", 1)[1].lower()
    if ext not in ALLOWED:
        raise UploadRejected(f"'.{ext}' files are not allowed. Allowed: {', '.join(sorted(ALLOWED))}.")
    max_bytes = current_app.config.get("MAX_UPLOAD_MB", 10) * 1024 * 1024
    if not data:
        raise UploadRejected("File is empty.")
    if len(data) > max_bytes:
        raise UploadRejected(f"File is larger than {current_app.config.get('MAX_UPLOAD_MB', 10)} MB.")
    types, magic = ALLOWED[ext]
    if content_type and content_type.split(";")[0].strip().lower() not in types | {"application/octet-stream"}:
        raise UploadRejected("File type does not match its extension.")
    if magic is not None:
        if not any(data.startswith(m) for m in magic):
            raise UploadRejected("File contents do not match its extension.")
        if ext == "webp" and data[8:12] != b"WEBP":
            raise UploadRejected("File contents do not match its extension.")
    else:
        try:
            data[:4096].decode("utf-8")
        except UnicodeDecodeError:
            raise UploadRejected("Text files must be UTF-8.")
    return ext


class LocalStorage:
    def __init__(self, root: str):
        self.root = os.path.abspath(root)

    def _path(self, key: str) -> str:
        path = os.path.abspath(os.path.join(self.root, key))
        if not path.startswith(self.root + os.sep):
            raise ValueError("Invalid storage key.")
        return path

    def put(self, organization_id: str, ext: str, data: bytes) -> tuple[str, str]:
        key = f"{organization_id}/{uuid.uuid4().hex}.{ext}"
        path = self._path(key)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as fh:
            fh.write(data)
        return key, hashlib.sha256(data).hexdigest()

    def get(self, key: str) -> bytes:
        with open(self._path(key), "rb") as fh:
            return fh.read()

    def delete(self, key: str) -> None:
        try:
            os.remove(self._path(key))
        except FileNotFoundError:
            pass


class StorageUnavailable(ServiceUnavailable):
    """The remote storage service rejected the request or could not be reached.
    Returned to the client as a 503 with this message (no internals)."""


# Keys are always generated by put(): "<org uuid>/<hex>.<ext>".
_KEY_RE = re.compile(r"^[0-9a-fA-F-]{1,64}/[0-9a-f]{32}\.[a-z0-9]{1,10}$")


class SupabaseStorage:
    """Private bucket in Supabase Storage, via its REST API.

    Uses the project's secret (service role) key, so it runs only on the
    server; the bucket should be private and is never exposed to browsers.
    """

    def __init__(self, base_url: str, secret_key: str, bucket: str, timeout: int = 20):
        if not base_url or not secret_key:
            raise StorageUnavailable("Supabase storage is not configured (SUPABASE_URL / SUPABASE_SECRET_KEY).")
        self.base = base_url.rstrip("/") + "/storage/v1/object"
        self.bucket = bucket
        self.timeout = timeout
        self.headers = {"apikey": secret_key}
        # Legacy service_role keys are JWTs and also go in Authorization; the
        # newer sb_secret_ keys are sent only as apikey.
        if secret_key.startswith("eyJ"):
            self.headers["Authorization"] = f"Bearer {secret_key}"

    def _url(self, key: str, prefix: str = "") -> str:
        if not _KEY_RE.match(key):
            raise ValueError("Invalid storage key.")
        return f"{self.base}/{prefix}{urllib.parse.quote(self.bucket)}/{key}"

    def _request(self, method: str, url: str, data: bytes | None = None, content_type: str | None = None) -> bytes:
        headers = dict(self.headers)
        if content_type:
            headers["Content-Type"] = content_type
        req = urllib.request.Request(url, data=data, headers=headers, method=method)
        try:
            # Fixed host from server config, not user input.
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:  # noqa: S310
                return resp.read()
        except urllib.error.HTTPError as exc:
            if exc.code in (400, 404) and method == "DELETE":
                return b""
            raise StorageUnavailable(f"Supabase storage returned HTTP {exc.code}.") from exc
        except (urllib.error.URLError, TimeoutError) as exc:
            raise StorageUnavailable("Supabase storage could not be reached.") from exc

    def put(self, organization_id: str, ext: str, data: bytes) -> tuple[str, str]:
        key = f"{organization_id}/{uuid.uuid4().hex}.{ext}"
        types, _ = ALLOWED.get(ext, ({"application/octet-stream"}, None))
        self._request("POST", self._url(key), data=data, content_type=sorted(types)[0])
        return key, hashlib.sha256(data).hexdigest()

    def get(self, key: str) -> bytes:
        return self._request("GET", self._url(key, prefix="authenticated/"))

    def delete(self, key: str) -> None:
        self._request("DELETE", self._url(key))


def get_storage() -> LocalStorage | SupabaseStorage:
    cfg = current_app.config
    if cfg.get("STORAGE_BACKEND") == "supabase":
        return SupabaseStorage(cfg.get("SUPABASE_URL", ""), cfg.get("SUPABASE_SECRET_KEY", ""),
                               cfg.get("SUPABASE_STORAGE_BUCKET", "arc-uploads"))
    return LocalStorage(cfg.get("UPLOAD_DIR", "storage/uploads"))
